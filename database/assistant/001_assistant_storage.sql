/*
  Artin assistant: per-user notes, reminders, timers, memory, browser push
  subscriptions, and the daily briefing summary.

  Safe to run more than once. Requires SQL Server 2016 SP1 or later.
  Times are stored as Unix epoch milliseconds (BIGINT) so the server's time
  zone and the driver's UTC setting cannot shift a reminder.
*/

IF OBJECT_ID(N'dbo.tblAssistantItem', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.tblAssistantItem (
    id            BIGINT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_tblAssistantItem PRIMARY KEY,
    clientId      INT            NOT NULL,
    userId        INT            NOT NULL,
    itemKey       NVARCHAR(64)   NOT NULL,  -- id generated by the browser
    kind          NVARCHAR(16)   NOT NULL,  -- note | reminder | timer | memory
    itemText      NVARCHAR(1000) NULL,
    dueAtMs       BIGINT         NULL,      -- reminders and timers only
    lang          NVARCHAR(8)    NULL,      -- 'hi' for requests made in Hindi
    createdAtMs   BIGINT         NOT NULL,
    updatedAtMs   BIGINT         NOT NULL,  -- last write wins
    deletedAtMs   BIGINT         NULL,      -- kept 30 days so other devices learn of it
    notifiedAtMs  BIGINT         NULL,      -- set when the push reminder was sent
    CONSTRAINT UQ_tblAssistantItem_user_key UNIQUE (userId, itemKey),
    CONSTRAINT CK_tblAssistantItem_kind CHECK (kind IN (N'note', N'reminder', N'timer', N'memory'))
  );

  CREATE INDEX IX_tblAssistantItem_due
    ON dbo.tblAssistantItem (dueAtMs)
    INCLUDE (userId, kind)
    WHERE deletedAtMs IS NULL AND notifiedAtMs IS NULL AND dueAtMs IS NOT NULL;
END
GO

IF OBJECT_ID(N'dbo.tblAssistantPushSubscription', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.tblAssistantPushSubscription (
    id          BIGINT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_tblAssistantPushSubscription PRIMARY KEY,
    clientId    INT           NOT NULL,
    userId      INT           NOT NULL,
    endpoint    NVARCHAR(800) NOT NULL,
    p256dh      NVARCHAR(200) NOT NULL,
    authKey     NVARCHAR(100) NOT NULL,
    userAgent   NVARCHAR(300) NULL,
    createdAt   DATETIME2(0)  NOT NULL CONSTRAINT DF_tblAssistantPushSubscription_createdAt DEFAULT SYSUTCDATETIME(),
    lastSeenAt  DATETIME2(0)  NOT NULL CONSTRAINT DF_tblAssistantPushSubscription_lastSeenAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_tblAssistantPushSubscription_endpoint UNIQUE (endpoint)
  );

  CREATE INDEX IX_tblAssistantPushSubscription_user
    ON dbo.tblAssistantPushSubscription (userId);
END
GO

